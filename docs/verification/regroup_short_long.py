"""Regroup our T4 results into the paper's Table 3 hop groups: Short (2-6) and Long (7-10).

The paper's Table 3 (p. 8) reports accuracy for hops 2-6 and 7-10. Our summaries use 2-4 / 5-7 / 8-10, so this
script rescores the committed raw run files with the repo's own scorer (experiments/_shared/score.py,
SQuAD-normalised EM) and prints EM [95% bootstrap CI over questions, 2000 resamples, seed 0] per hop group.

Inputs (all committed):
  results/t4/s1/NaiveReason_*_k20.jsonl             one call, 900 questions (slice s900)
  results/t4/s2/SequentialReason_*_k20_s5.jsonl     5 steps, 306 questions (slice s306, a subset of s900)

NR is shown on its 900 questions and on the 306 questions that SR also answered (same keys uid:rc_id).

Usage (from the repo root): python docs/verification/regroup_short_long.py > docs/verification/regroup_short_long.md
Stdlib only.
"""

import importlib.util
import json
import random
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
spec = importlib.util.spec_from_file_location(
    "score", ROOT / "experiments/_shared/score.py"
)
score = importlib.util.module_from_spec(spec)
spec.loader.exec_module(score)

MEMS = [
    ("Ignoramus", "no memory"),
    ("Oracle", "Oracle"),
    ("SparseRAG", "BM25"),
    ("DenseRAG", "e5"),
]
GROUPS = {"short 2-6": range(2, 7), "long 7-10": range(7, 11), "all 2-10": range(2, 11)}


def load(path):
    out = {}
    with open(path, encoding="utf-8") as f:
        for line in f:
            if line.strip():
                r = json.loads(line)
                out[f"{r['uid']}:{r['rc_id']}"] = r
    return out


def boot(vals, seed=0, B=2000):
    rng = random.Random(seed)
    n = len(vals)
    means = sorted(sum(vals[rng.randrange(n)] for _ in range(n)) / n for _ in range(B))
    return means[int(0.025 * B)], means[int(0.975 * B) - 1]


def cell(rows, hops):
    v = [
        1.0 if score.em(r["response"], r["ground_truth"]) else 0.0
        for r in rows
        if int(r["k_hop"]) in hops
    ]
    m = sum(v) / len(v)
    lo, hi = boot(v)
    return len(v), m, lo, hi


def main():
    nr = {m: load(ROOT / f"results/t4/s1/NaiveReason_{m}_k20.jsonl") for m, _ in MEMS}
    sr = {
        m: load(ROOT / f"results/t4/s2/SequentialReason_{m}_k20_s5.jsonl")
        for m, _ in MEMS
    }
    keys306 = set(sr["Oracle"])
    print(
        "# Our results in the paper's Table 3 hop groups (generated by docs/verification/regroup_short_long.py)\n"
    )
    print(
        "EM [95% CI], bootstrap over questions (2000 resamples, seed 0), Qwen2.5-7B-Instruct-AWQ on a T4, k = 20, greedy, our scorer.\n"
    )
    print("| setting | memory | group | n | EM [95% CI] |")
    print("|---|---|---|---|---|")
    for label, runs, restrict in [
        ("NR one call, 900 q", nr, None),
        ("NR one call, 306 q", nr, keys306),
        ("SR 5 steps, 306 q", sr, None),
    ]:
        for m, name in MEMS:
            rows = [r for k, r in runs[m].items() if restrict is None or k in restrict]
            for g, hops in GROUPS.items():
                n, mean, lo, hi = cell(rows, hops)
                print(
                    f"| {label} | {name} | {g} | {n} | {mean:.3f} [{lo:.3f}, {hi:.3f}] |"
                )


if __name__ == "__main__":
    main()
