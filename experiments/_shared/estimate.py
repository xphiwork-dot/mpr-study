"""Planning estimates for sessions 2-3 from measured session-1 numbers (no new runs). Writes results/t4/estimates.md.

Model: the T4 run is prefill-bound (throughput.jsonl: ~1.1-1.2k prompt tokens/s no matter the concurrency), so
minutes = prompt tokens / measured prompt-token rate. Prompt tokens per call come from results/t4/s1/timing.jsonl
(k = 20 runs; the token count is linear in k, slope from Ignoramus vs RAG) and from the 6-question SR smoke run
results/t4/smoke_seq (tokens per question for 5 steps). These are rough: the SR smoke sample is small and the
SR step sweep assumes tokens per call stay constant across step counts (previous thoughts make later calls longer,
so long chains are underestimated). Sessions 2-4 have NOT been run.
"""
import glob
import json
import os

T4 = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "results", "t4")


def rows(path):
    return [json.loads(l) for l in open(path) if l.strip()]


def main():
    tim = {r["file"]: r for r in rows(os.path.join(T4, "s1", "timing.jsonl")) if r["calls"]}
    thr = {r["phase"]: r for r in rows(os.path.join(T4, "throughput", "throughput.jsonl"))}
    sr_rate = thr["seq5_sparse_c64"]["prompt_tok_per_s"]
    per_call = {k.split("_")[1]: v["prompt_tokens"] / v["calls"] for k, v in tim.items()}
    rate = {k.split("_")[1]: v["prompt_tokens"] / v["wall_s"] for k, v in tim.items()}
    slope = {m: (per_call[m] - per_call["Ignoramus"]) / 20 for m in ("SparseRAG", "DenseRAG")}
    smoke = {}
    for f in glob.glob(os.path.join(T4, "smoke_seq", "SequentialReason_*_s5.jsonl")):
        rs = rows(f)
        smoke[os.path.basename(f).split("_")[1]] = sum(r["prompt_tokens"] for r in rs) / len(rs)
    L = ["# Planning estimates for sessions 2-3 (generated by experiments/_shared/estimate.py)", "",
         "Estimates only, from session-1 measurements; the real timings of the sessions that were run are in `timing_log.md`. See the module docstring for the model.", "",
         f"Measured prompt rate: NR runs {', '.join(f'{m} {rate[m]:.0f}' for m in rate)} tok/s; SR throughput phase {sr_rate} tok/s.", "",
         "## Session 2: SequentialReason, 5 steps, 306 questions", "", "| memory | prompt tokens/question (smoke, n=6) | est. minutes |", "|---|---|---|"]
    tot = 0
    for m, t in smoke.items():
        mins = 306 * t / sr_rate / 60
        tot += mins
        L.append(f"| {m} | {t:.0f} | {mins:.1f} |")
    L += [f"| total | | {tot:.1f} |", "", "## Session 3a: NR top-k sweep, 900 questions, BM25 and e5", "", "| k | memory | prompt tokens/call | est. minutes |", "|---|---|---|---|"]
    tot3 = 0
    for k in (10, 30, 50):
        for m in ("SparseRAG", "DenseRAG"):
            t = per_call["Ignoramus"] + slope[m] * k
            mins = 900 * t / rate[m] / 60
            tot3 += mins
            L.append(f"| {k} | {m} | {t:.0f} | {mins:.1f} |")
    L += [f"| total | | | {tot3:.1f} |", "", "## Session 3b: SR step sweep (2, 3, 8 steps), 306 questions, BM25 and e5, k = 20", "",
          "Assumes tokens per call equal the 5-step average (underestimates 8 steps).", "", "| steps | memory | est. minutes |", "|---|---|---|"]
    tot3b = 0
    for s in (2, 3, 8):
        for m in ("SparseRAG", "DenseRAG"):
            mins = 306 * smoke[m] / 5 * s / sr_rate / 60
            tot3b += mins
            L.append(f"| {s} | {m} | {mins:.1f} |")
    L += [f"| total | | {tot3b:.1f} |", "", f"Session 3 total (3a + 3b): {tot3 + tot3b:.1f} minutes of generation, plus about 5 minutes of setup.", ""]
    out = os.path.join(T4, "estimates.md")
    open(out, "w").write("\n".join(L))
    print("\n".join(L))


if __name__ == "__main__":
    main()
